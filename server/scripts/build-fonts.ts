/**
 * Font assembly: copy only the woff2 subsets we use into public/assets/fonts, and generate
 * a fonts-generated.ts module of tree-shakeable @font-face CSS keyed by family. The renderer
 * emits @font-face ONLY for the fonts a given page's pair uses. Self-hosted (no font CDN),
 * font-display:swap, unicode-range split so Latin pages never fetch Arabic glyphs and vice-versa.
 */
import { mkdirSync, copyFileSync, writeFileSync, existsSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'

const require = createRequire(import.meta.url)
const OUT_FONTS = path.resolve('public/assets/fonts')
const OUT_MODULE = path.resolve('src/render/fonts-generated.ts')

const UR_LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+2074,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD'
const UR_ARABIC = 'U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0898-08E1,U+08E3-08FF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,U+FE70-FE74,U+FE76-FEFC,U+FEFF'

type Entry = {
  family: string; id: string; pkg: string; subset: 'latin' | 'arabic'
  variable?: { range: string; file?: string }
  weights?: number[]
}

const MANIFEST: Entry[] = [
  { family: 'Inter', id: 'inter', pkg: '@fontsource-variable/inter', subset: 'latin', variable: { range: '100 900' } },
  { family: 'Space Grotesk', id: 'space-grotesk', pkg: '@fontsource-variable/space-grotesk', subset: 'latin', variable: { range: '300 700' } },
  { family: 'Fraunces', id: 'fraunces', pkg: '@fontsource-variable/fraunces', subset: 'latin', variable: { range: '100 900', file: 'fraunces-latin-wght-normal.woff2' } },
  { family: 'Sora', id: 'sora', pkg: '@fontsource-variable/sora', subset: 'latin', variable: { range: '100 800' } },
  { family: 'IBM Plex Sans', id: 'ibm-plex-sans', pkg: '@fontsource/ibm-plex-sans', subset: 'latin', weights: [400, 600, 700] },
  { family: 'Cairo', id: 'cairo', pkg: '@fontsource-variable/cairo', subset: 'arabic', variable: { range: '200 1000' } },
  { family: 'Rubik', id: 'rubik', pkg: '@fontsource-variable/rubik', subset: 'arabic', variable: { range: '300 900' } },
  { family: 'Tajawal', id: 'tajawal', pkg: '@fontsource/tajawal', subset: 'arabic', weights: [400, 700] },
  { family: 'IBM Plex Sans Arabic', id: 'ibm-plex-sans-arabic', pkg: '@fontsource/ibm-plex-sans-arabic', subset: 'arabic', weights: [400, 600, 700] },
]

function filesDir(pkg: string) {
  return path.join(path.dirname(require.resolve(pkg + '/package.json')), 'files')
}
const ur = (s: 'latin' | 'arabic') => (s === 'latin' ? UR_LATIN : UR_ARABIC)

function main() {
  mkdirSync(OUT_FONTS, { recursive: true })
  const faces: Record<string, string> = {}
  const files: Record<string, string> = {}

  for (const e of MANIFEST) {
    const dir = filesDir(e.pkg)
    const css: string[] = []
    if (e.variable) {
      const srcName = e.variable.file ?? `${e.id}-${e.subset}-wght-normal.woff2`
      const dest = `${e.id}-${e.subset}.woff2`
      copyFileSync(path.join(dir, srcName), path.join(OUT_FONTS, dest))
      const url = `/assets/fonts/${dest}`
      css.push(`@font-face{font-family:"${e.family}";font-style:normal;font-weight:${e.variable.range};font-display:swap;src:url(${url}) format("woff2");unicode-range:${ur(e.subset)}}`)
      files[e.family] = url
    } else {
      for (const w of e.weights!) {
        const srcName = `${e.id}-${e.subset}-${w}-normal.woff2`
        const dest = `${e.id}-${e.subset}-${w}.woff2`
        copyFileSync(path.join(dir, srcName), path.join(OUT_FONTS, dest))
        const url = `/assets/fonts/${dest}`
        css.push(`@font-face{font-family:"${e.family}";font-style:normal;font-weight:${w};font-display:swap;src:url(${url}) format("woff2");unicode-range:${ur(e.subset)}}`)
        if (w === 600 || (w === 700 && !files[e.family])) files[e.family] = url
        if (!files[e.family]) files[e.family] = url
      }
    }
    faces[e.family] = css.join('')
  }

  const header = '// AUTO-GENERATED by scripts/build-fonts.ts — do not edit by hand.\n'
  const body =
    `export const FONT_FACES: Record<string, string> = ${JSON.stringify(faces, null, 2)}\n\n` +
    `export const FONT_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)}\n`
  writeFileSync(OUT_MODULE, header + body)
  console.log(`fonts: copied ${MANIFEST.length} families -> public/assets/fonts, wrote ${path.relative(process.cwd(), OUT_MODULE)}`)
}
main()
